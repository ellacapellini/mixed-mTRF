"""
recovery_grid.py
=================

THE fix for the flaw in compare.py's original design: that comparison
generated ONE synthetic dataset from Model A's generative process and
asked all seven models to predict it -- which was never a fair test
for Model B (it was being scored on data it wasn't built to generate),
and it couldn't distinguish "Model B's sampler is broken" from "Model
B is just the wrong model for this particular data."

WHAT THIS DOES INSTEAD: a model-recovery / confusion matrix (standard
practice in computational modelling, e.g. Wilson & Collins 2019 "Ten
simple rules for computational modeling of behavioral data"). Seven
generators x seven fitters = 49 cells (Standard included as its own
generator -- see below; an earlier version of this file wrongly
excluded it as "nested inside A-B1", which is true in principle but
meant the single most basic sanity check, "can the harness recover
the simplest possible ground truth at all", was never actually run).
The diagonal (fit model X on data generated by X) is the direct
answer to today's question: can the sampler recover known ground truth
from its OWN model, independent of any generator/fitter mismatch? The
off-diagonal cells show how much models can mimic each other's data,
which is exactly the information WAIC/LOO needs context from.

NAMING: this file uses "A-B1"/"A-B2"/"B-Matern-B1"/... throughout, NOT
the equations doc's "A-C1"/"A-C2"/"B-C1"/"B-C2" naming. That's a real
naming drift between the doc and the code (bayesian_mixed_trf.py's
variant strings are literally "A-B1"/"A-B2", and fit_bayesian_mixed_trf
raises ValueError on anything else) -- worth reconciling in the doc
at some point, but this file matches the CODE's naming since it calls
that code directly.

GENERATORS: six generators reuse existing, already self-tested code
(nothing here duplicates a generative process, only wires existing
pieces together), plus a seventh added for completeness after review:
  Standard    : ground_truth.py's make_stage1_static -- beta=0, NO
                hierarchy (a single shared h(tau) for every unit).
                This is not a stylistic placeholder: it's the actual
                null-model ground truth Standard's own ridge fit
                assumes, and Standard->Standard is the cheapest, most
                basic sanity check in the whole grid -- if design
                matrix construction, SNR scaling, or the ridge fit
                itself were subtly wrong, THIS is the cell that would
                catch it, before blaming anything model-specific.
  A-B1        : make_stage2_amplitude_only (beta_j = gain*mu_j) + hierarchy.
  A-B2        : make_stage3_full_modulation (beta_j free per basis function)
                + hierarchy.
  B-Matern-B1 : ground_truth_gp.py's make_stage3_full_modulation,
                kernel_type="matern52", delta=None (B1) + hierarchy.
  B-Matern-B2 : same, delta/gamma set (B2, added in the previous session).
  B-SE-B1     : same as B-Matern-B1, kernel_type="squared_exponential".
  B-SE-B2     : same as B-Matern-B2, kernel_type="squared_exponential".

FITTERS: exactly compare.py's seven fit_predict_* functions, imported
and reused directly, not reimplemented -- the grid's whole point is to
stress-test those exact fitters on harder-to-mismatch data, not to
introduce a second parallel fitting implementation that could itself
drift from compare.py's.

SCALE: a full 42-cell grid at compare.py's production settings
(n_patients=4, n_electrodes=3, draws=500, tune=1000, chains=4) would
take on the order of a full day, given individual Bayesian fits were
already taking 15-80 minutes each on the shared-dataset run, and some
(SE-B1/B2) took 4900-9200s (over an hour) each. Default here is a much
smaller PILOT scale (fewer patients/electrodes/lags/draws/tune) so the
whole grid finishes in a practical amount of time and tells you, TODAY,
whether the funnel problem is generator/fitter-mismatch-specific or
present even on each model's own home turf. Bump to scale="full" (or
pass explicit sizes) once the pilot grid tells you which cells are
worth the expensive rerun.

CHECKPOINTING: each cell is fit, scored, and immediately written to
results_path as JSON before moving to the next cell. Re-running this
script with the same results_path picks up where it left off (skips
any (generator, fitter) pair already present) rather than restarting
the whole grid -- necessary given how likely a 42-cell run is to get
interrupted at full scale.
"""

